"""Generate build/version_info.txt for PyInstaller.

Windows exes without a version resource (no product name, no company, no
version) score noticeably worse with Defender's ML heuristics. This writes a
real VERSIONINFO block so HabitFlow.exe identifies itself properly in the
file's Details tab.

Version comes from $HABITFLOW_VERSION (the release tag, e.g. "v1.2.0") and
falls back to APP_VERSION in app.py.

    python packaging/make_version.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'packaging', 'version_info.txt')

TEMPLATE = """\
# UTF-8, generated by packaging/make_version.py, do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({a}, {b}, {c}, 0),
    prodvers=({a}, {b}, {c}, 0),
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName',      'HabitFlow (open source)'),
        StringStruct('FileDescription',  'HabitFlow - offline daily habit tracker'),
        StringStruct('FileVersion',      '{dotted}'),
        StringStruct('InternalName',     'HabitFlow'),
        StringStruct('LegalCopyright',   'Apache License 2.0'),
        StringStruct('OriginalFilename', 'HabitFlow.exe'),
        StringStruct('ProductName',      'HabitFlow'),
        StringStruct('ProductVersion',   '{dotted}'),
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def app_version():
    with open(os.path.join(ROOT, 'app.py'), encoding='utf-8') as fh:
        match = re.search(r"^APP_VERSION\s*=\s*['\"]([^'\"]+)", fh.read(), re.M)
    return match.group(1) if match else '0.0.0'


def main():
    raw = (os.environ.get('HABITFLOW_VERSION') or app_version()).lstrip('vV')
    parts = re.findall(r'\d+', raw)[:3]
    while len(parts) < 3:
        parts.append('0')
    a, b, c = (int(p) for p in parts)
    dotted = f'{a}.{b}.{c}'
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(TEMPLATE.format(a=a, b=b, c=c, dotted=dotted))
    print(dotted)
    return dotted


if __name__ == '__main__':
    sys.stdout.write('')
    main()
